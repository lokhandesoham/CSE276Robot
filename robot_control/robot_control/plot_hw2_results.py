"""Render the 2D car trajectory dot plot (Report Section 1i) and LaTeX pgfplots coordinates.

Reads `hw2_trajectory.csv` and `hw2_summary.json` generated by `closed_loop_follower`
and outputs:
  1. `hw2_trajectory_plot.png` (high-res 2D trajectory plot with 0.5s red dots,
     axes arrows, reference triangle, and landmarks — rendered via OpenCV so it works
     out-of-the-box without requiring matplotlib).
  2. Prints LaTeX `pgfplots` coordinates and summary table rows for `report/report-hw2.tex`.

Usage:
    ros2 run robot_control plot_hw2_results
    python3 -m robot_control.plot_hw2_results --csv hw2_trajectory.csv --out hw2_trajectory_plot.png
"""

import argparse
import csv
import json
import os

import cv2
import numpy as np


def render_trajectory_png(samples, out_path, use_units=True):
    """Draw a clean 2D trajectory image with a red dot every 0.5s (Report 1i)."""
    width, height = 900, 950
    img = np.full((height, width, 3), 255, dtype=np.uint8)

    # Coordinate range in units: x in [-1.0, 2.4], y in [-0.7, 3.3]
    x_min, x_max = -1.0, 2.4
    y_min, y_max = -0.7, 3.3

    margin_l, margin_r = 95, 55
    margin_t, margin_b = 70, 85
    plot_w = width - margin_l - margin_r
    plot_h = height - margin_t - margin_b

    def to_px(x_u, y_u):
        u = int(round(margin_l + (x_u - x_min) / (x_max - x_min) * plot_w))
        v = int(round(height - margin_b - (y_u - y_min) / (y_max - y_min) * plot_h))
        return u, v

    # Light grid lines every 0.5 units
    for gx in np.arange(-0.5, 2.5, 0.5):
        u0, v0 = to_px(gx, y_min)
        u1, v1 = to_px(gx, y_max)
        cv2.line(img, (u0, v0), (u1, v1), (235, 235, 235), 1, cv2.LINE_AA)
    for gy in np.arange(-0.5, 3.5, 0.5):
        u0, v0 = to_px(x_min, gy)
        u1, v1 = to_px(x_max, gy)
        cv2.line(img, (u0, v0), (u1, v1), (235, 235, 235), 1, cv2.LINE_AA)

    # Draw main X and Y axes through (0, 0) with arrows (matching HW2 prompt diagram)
    ox, oy = to_px(0.0, 0.0)
    x_end = to_px(2.25, 0.0)
    y_end = to_px(0.0, 3.15)
    x_start = to_px(-0.85, 0.0)
    y_start = to_px(0.0, -0.55)

    cv2.arrowedLine(img, x_start, x_end, (20, 20, 20), 3, cv2.LINE_AA, tipLength=0.025)
    cv2.arrowedLine(img, y_start, y_end, (20, 20, 20), 3, cv2.LINE_AA, tipLength=0.025)
    cv2.putText(
        img, 'X (units)', (x_end[0] - 45, x_end[1] + 35),
        cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 0, 0), 2, cv2.LINE_AA
    )
    cv2.putText(
        img, 'Y (units)', (y_end[0] + 12, y_end[1] + 10),
        cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 0, 0), 2, cv2.LINE_AA
    )

    # Tick labels along axes
    for tick_x in [1.0, 2.0]:
        tx, ty = to_px(tick_x, 0.0)
        cv2.line(img, (tx, ty - 5), (tx, ty + 5), (0, 0, 0), 2)
        cv2.putText(
            img, f'{tick_x:.0f}', (tx - 8, ty + 25),
            cv2.FONT_HERSHEY_SIMPLEX, 0.55, (40, 40, 40), 1, cv2.LINE_AA
        )
    for tick_y in [1.0, 2.0, 3.0]:
        tx, ty = to_px(0.0, tick_y)
        cv2.line(img, (tx - 5, ty), (tx + 5, ty), (0, 0, 0), 2)
        cv2.putText(
            img, f'{tick_y:.0f}', (tx - 28, ty + 6),
            cv2.FONT_HERSHEY_SIMPLEX, 0.55, (40, 40, 40), 1, cv2.LINE_AA
        )

    # Draw dashed reference triangle (0,0) -> (1,0) -> (1,2) -> (0,0)
    wps = [(0.0, 0.0), (1.0, 0.0), (1.0, 2.0), (0.0, 0.0)]
    for i in range(len(wps) - 1):
        p0 = to_px(*wps[i])
        p1 = to_px(*wps[i + 1])
        cv2.line(img, p0, p1, (180, 180, 180), 2, cv2.LINE_AA)

    # Draw known landmarks as blue squares
    landmarks = [
        ('LM0: coke_can', 2.0, 0.0),
        ('LM1: backpack', 1.8, 1.0),
        ('LM2: tv_monitor', 1.0, 3.0),
        ('LM3: sports_ball', -0.6, 2.0),
        ('LM4: chair', -0.6, -0.4),
    ]
    for name, lx, ly in landmarks:
        lu, lv = to_px(lx, ly)
        cv2.rectangle(img, (lu - 7, lv - 7), (lu + 7, lv + 7), (200, 90, 0), -1)
        cv2.putText(
            img, name, (lu + 10, lv + 5),
            cv2.FONT_HERSHEY_SIMPLEX, 0.48, (160, 70, 0), 1, cv2.LINE_AA
        )

    # Draw 0.5s estimated trajectory red dots
    for s in samples:
        xu = float(s['x_unit']) if use_units else float(s['x_m'])
        yu = float(s['y_unit']) if use_units else float(s['y_m'])
        px, py = to_px(xu, yu)
        cv2.circle(img, (px, py), 5, (30, 30, 225), -1, cv2.LINE_AA)

    # Title
    cv2.putText(
        img, 'HW2 Estimated 2D Trajectory (0.5s Sample Dots, 1 unit = 0.5m)',
        (margin_l, 42), cv2.FONT_HERSHEY_SIMPLEX, 0.72, (20, 20, 20), 2, cv2.LINE_AA
    )

    cv2.imwrite(out_path, img)


def main(args=None):
    parser = argparse.ArgumentParser(description='Plot HW2 2D trajectory & LaTeX snippets')
    parser.add_argument('--csv', default='hw2_trajectory.csv', help='Path to trajectory CSV')
    parser.add_argument('--summary', default='hw2_summary.json', help='Path to summary JSON')
    parser.add_argument('--out', default='hw2_trajectory_plot.png', help='Output PNG path')
    parsed, _ = parser.parse_known_args(args=args)

    if not os.path.exists(parsed.csv):
        print(f'No trajectory file found at {parsed.csv}. Run closed_loop_follower first.')
        return 1

    with open(parsed.csv, 'r') as f:
        samples = list(csv.DictReader(f))

    render_trajectory_png(samples, parsed.out, use_units=True)
    print(f'Saved 2D trajectory plot to: {os.path.abspath(parsed.out)}')

    # Print pgfplots coordinates for report-hw2.tex
    coords_str = ' '.join(
        f'({float(s["x_unit"]):.3f},{float(s["y_unit"]):.3f})' for s in samples
    )
    print('\n--- LaTeX pgfplots snippet (units) ---')
    print(f'\\addplot[only marks, mark=*, mark size=1.6pt, red] coordinates {{{coords_str}}};')

    if os.path.exists(parsed.summary):
        with open(parsed.summary, 'r') as f:
            summary = json.load(f)
        print('\n--- Waypoint Error Summary ---')
        for wp in summary.get('waypoint_errors', []):
            print(
                f'WP {wp["waypoint_index"]} {wp["target_units"]}: '
                f'Est={wp["estimated_units"]} | '
                f'Trans Err={wp["translation_error_cm"]:.2f} cm '
                f'({wp["translation_error_units"]:.3f} u) | '
                f'Rot Err={wp["rotation_error_deg"]:+.2f} deg'
            )
    return 0


if __name__ == '__main__':
    main()
